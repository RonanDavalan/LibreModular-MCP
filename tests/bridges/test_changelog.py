"""Tests of scripts/generate_changelog.py.

Why this module exists
The changelog must come from the commit titles and nothing else, and its check must
notice a file that no longer matches the history. The text is compared with the
exact output for a fixed log written here, never with the living history, which a
new commit would make stale; each check is shown failing on a script broken on purpose.
"""

import os
import pathlib
import subprocess
import sys
import unittest

from bridge_support import PrivateDir, defective_text, load_text

SCRIPT = pathlib.Path(__file__).resolve().parents[2] / "scripts" / "generate_changelog.py"
SCRIPT_TEXT = SCRIPT.read_text(encoding="utf-8")


def load(text=SCRIPT_TEXT):
    return load_text(text, "lmm_generate_changelog", str(SCRIPT))


CHANGELOG = load()

# Newest first, as `git log` gives them.
FIXED_LOG = [
    "Add the third thing",
    "Fix a defect of the second thing",
    "Merge pull request #7 from alice/feature",
    "Document how the second thing starts",
    "",
    "Test the second thing against a fake",
    "Wait before connecting a second time",
    "Check that nothing else starts a process",
    "Add the first thing",
]

EXPECTED = """\
# Changelog

Generated by scripts/generate_changelog.py from the titles of the commits. Do not edit by hand.

## Unreleased

### Added

- Add the third thing
- Add the first thing

### Fixed

- Fix a defect of the second thing

### Documentation

- Document how the second thing starts

### Tests

- Test the second thing against a fake
- Check that nothing else starts a process

### Changed

- Wait before connecting a second time
"""


def misfiles_a_title():
    """The script with a title put in the wrong section: `Fix` no longer is a fix."""
    return load(
        defective_text(
            SCRIPT_TEXT,
            '("Fixed", ("Fix", "Correct", "Repair")),',
            '("Fixed", ("Correct", "Repair")),',
        )
    )


def never_notices_a_stale_file():
    return load(
        defective_text(
            SCRIPT_TEXT,
            "        if current != text:\n            sys.stderr.write(\"CHANGELOG.md is out of date",
            "        if False:\n            sys.stderr.write(\"CHANGELOG.md is out of date",
        )
    )


def check_the_exact_output_for_a_fixed_log(module):
    produced = module.render(FIXED_LOG)
    return [] if produced == EXPECTED else ["produced:\n" + produced]


GIT_ENVIRONMENT = {
    "PATH": os.environ.get("PATH", ""),
    "GIT_CONFIG_GLOBAL": os.devnull,
    "GIT_CONFIG_NOSYSTEM": "1",
    "GIT_AUTHOR_NAME": "Alice",
    "GIT_AUTHOR_EMAIL": "alice@example.invalid",
    "GIT_COMMITTER_NAME": "Alice",
    "GIT_COMMITTER_EMAIL": "alice@example.invalid",
}


def git(repository, *arguments):
    subprocess.run(
        ["git", "-C", str(repository), *arguments],
        check=True,
        capture_output=True,
        env=GIT_ENVIRONMENT,
        timeout=60,
    )


def repository_with(directory, titles):
    """A new repository under `directory` holding one empty commit per title,
    oldest first."""
    path = directory.path / "repository"
    path.mkdir()
    git(path, "init", "-q")
    for title in titles:
        git(path, "commit", "-q", "--allow-empty", "-m", title)
    return path


def run_main(module, arguments, root):
    saved = os.environ.copy()
    os.environ.clear()
    os.environ.update(GIT_ENVIRONMENT)
    try:
        return module.main(arguments, root=root)
    finally:
        os.environ.clear()
        os.environ.update(saved)


def check_the_check_follows_the_history(module):
    """A file made from the history passes the check; a new commit, or a hand edit,
    makes it fail; generating it again makes it pass."""
    problems = []
    directory = PrivateDir()
    try:
        root = repository_with(directory, ["Add the first thing", "Fix the first thing"])
        stderr = sys.stderr
        sys.stderr = open(os.devnull, "w")
        try:
            if run_main(module, [], root) != 0:
                problems.append("the file could not be generated")
            if run_main(module, ["--check"], root) != 0:
                problems.append("a file just generated failed the check")
            git(root, "commit", "-q", "--allow-empty", "-m", "Add the second thing")
            if run_main(module, ["--check"], root) == 0:
                problems.append("a file older than the history passed the check")
            run_main(module, [], root)
            if run_main(module, ["--check"], root) != 0:
                problems.append("the regenerated file failed the check")
            target = root / "CHANGELOG.md"
            target.write_text(target.read_text(encoding="utf-8") + "- by hand\n", encoding="utf-8")
            if run_main(module, ["--check"], root) == 0:
                problems.append("a file edited by hand passed the check")
        finally:
            sys.stderr.close()
            sys.stderr = stderr
    finally:
        directory.cleanup()
    return problems


class CheckCase(unittest.TestCase):
    def must_pass(self, problems):
        self.assertEqual(problems, [])

    def must_fail(self, problems):
        self.assertNotEqual(problems, [], "the check did not notice the defect")


class RenderTests(CheckCase):
    def test_the_output_for_a_fixed_log_is_exact(self):
        self.must_pass(check_the_exact_output_for_a_fixed_log(CHANGELOG))

    def test_counter_proof_a_script_that_misfiles_a_title_is_detected(self):
        self.must_fail(check_the_exact_output_for_a_fixed_log(misfiles_a_title()))

    def test_an_empty_history_says_so_and_nothing_else(self):
        text = CHANGELOG.render([])
        self.assertTrue(text.endswith("## Unreleased\n\nNothing yet.\n"), text)

    def test_a_title_starting_with_an_unknown_word_goes_to_changed(self):
        self.assertIn("### Changed\n\n- Frobnicate the widget\n", CHANGELOG.render(["Frobnicate the widget"]))

    def test_the_text_is_the_same_for_the_same_log(self):
        self.assertEqual(CHANGELOG.render(FIXED_LOG), CHANGELOG.render(list(FIXED_LOG)))


class CheckTests(CheckCase):
    def test_the_check_follows_the_history(self):
        self.must_pass(check_the_check_follows_the_history(CHANGELOG))

    def test_counter_proof_a_check_that_never_fails_is_detected(self):
        self.must_fail(check_the_check_follows_the_history(never_notices_a_stale_file()))

    def test_an_unknown_argument_is_a_usage_error(self):
        saved = sys.stderr
        sys.stderr = open(os.devnull, "w")
        try:
            self.assertEqual(CHANGELOG.main(["--bogus"]), 2)
        finally:
            sys.stderr.close()
            sys.stderr = saved


if __name__ == "__main__":
    unittest.main()
